/* global console */
// Copies self-hosted Japanese web fonts (fontsource) into public/fonts and
// generates fonts.css + manifest.json used by the preview and the PNG export.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const config = JSON.parse(
  fs.readFileSync(path.join(root, "src/data/fonts.json"), "utf8")
)
const outDir = path.join(root, "public/fonts")

const faceRe = /@font-face\s*{([^}]*)}/g
const prop = (body, name) => {
  const m = body.match(new RegExp(`${name}\\s*:\\s*([^;]+);`))
  return m ? m[1].trim() : undefined
}

fs.rmSync(outDir, { recursive: true, force: true })
fs.mkdirSync(outDir, { recursive: true })

const manifest = { faces: [] }
let css = "/* generated by scripts/build-fonts.mjs */\n"

for (const [key, def] of Object.entries(config.families)) {
  const pkgDir = path.join(root, "node_modules/@fontsource", def.package)
  if (!fs.existsSync(pkgDir)) {
    throw new Error(`@fontsource/${def.package} is not installed (${key})`)
  }
  const famOut = path.join(outDir, def.package)
  fs.mkdirSync(famOut, { recursive: true })
  for (const weight of def.weights) {
    const source = fs.readFileSync(path.join(pkgDir, `${weight}.css`), "utf8")
    for (const [, body] of source.matchAll(faceRe)) {
      const src = prop(body, "src")
      const range = prop(body, "unicode-range")
      const file = src?.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1]
      if (!file || !range) continue
      fs.copyFileSync(path.join(pkgDir, "files", file), path.join(famOut, file))
      const rel = `${def.package}/${file}`
      manifest.faces.push({
        key,
        family: def.family,
        weight,
        file: rel,
        unicodeRange: range,
      })
      css += `@font-face{font-family:'${def.family}';font-style:normal;font-display:swap;font-weight:${weight};src:url(./${rel}) format('woff2');unicode-range:${range};}\n`
    }
  }
}

fs.writeFileSync(path.join(outDir, "manifest.json"), JSON.stringify(manifest))
fs.writeFileSync(path.join(outDir, "fonts.css"), css)
console.log(`fonts: ${manifest.faces.length} faces written to public/fonts`)
